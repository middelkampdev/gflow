#!/usr/bin/env python3
"""Checks spec/cycles/*.json and renders them into spec/replay.html, the
replay page that shows each cycle step by step.

Usage: python3 spec/render.py
"""
import json
import re
import subprocess
import sys
from pathlib import Path

SPEC = Path(__file__).parent
CYCLES = SPEC / "cycles"
TEMPLATE = SPEC / "replay.template.html"
PAGE = SPEC / "replay.html"

HOOK_EVENTS = ("release-start", "release-bump", "release-finish", "hotfix-finish")

GENERATED_NOTICE = ("<!-- Generated by spec/render.py from spec/cycles/*.json and "
                    "spec/replay.template.html. Do not edit: change those, then run "
                    "python3 spec/render.py -->")


def problems(where, spec):
    """Everything in one cycle that the page could not follow: an unknown op,
    a commit without a version, an op on a missing branch, a PR out of
    order, a hook of an unknown event or tag, or a wrong deploy-version
    entry. Replays the ops by name only."""
    found = []
    for key in ("title", "settings", "rules", "actions"):
        if key not in spec:
            found.append(f"{where}: has no {key}")
    branches, tags, open_prs, next_pr = set(), set(), set(), 1

    for index, action in enumerate(spec.get("actions", [])):
        check_deploy_versions = lambda: [found.append(f"{where} action {index}: deployVersions {p}")
                                         for p in deploy_version_problems(action, branches)]
        for frame_index, frame in enumerate(action["frames"]):
            at = f"{where} action {index} frame {frame_index}"
            for op in frame["ops"]:
                kind = op["op"]

                def need(branch):
                    if branch not in branches:
                        found.append(f"{at}: {kind} of {branch}, which does not exist")

                def need_version(target):
                    if not isinstance(op.get("version"), str):
                        found.append(f"{at}: {kind} {target} has no version")

                if kind == "init":
                    branches.add(op.get("branch", "main"))
                    need_version("of the main line")
                elif kind in ("branch", "start"):
                    need(op["from"])
                    branches.add(op["name"])
                elif kind == "commit":
                    need(op["branch"])
                    need_version(f"on {op['branch']}")
                elif kind in ("squash", "merge"):
                    need(op["from"])
                    need(op["into"])
                    need_version(f"into {op['into']}")
                elif kind == "tag":
                    need(op["on"])
                    tags.add(op["name"])
                elif kind == "untag":
                    if op["name"] not in tags:
                        found.append(f"{at}: untag of {op['name']}, which does not exist")
                    tags.discard(op["name"])
                elif kind == "hook":
                    if op.get("event") not in HOOK_EVENTS:
                        found.append(f"{at}: hook of unknown event {op.get('event')}")
                    if op.get("tag") not in tags:
                        found.append(f"{at}: hook {op.get('event')} with tag {op.get('tag')}, which does not exist")
                elif kind == "delete":
                    need(op["name"])
                    branches.discard(op["name"])
                elif kind == "openPr":
                    if op["pr"] != next_pr:
                        found.append(f"{at}: PR #{op['pr']} opens, expected #{next_pr}")
                    next_pr = op["pr"] + 1
                    open_prs.add(op["pr"])
                elif kind == "mergedPr":
                    if op["pr"] not in open_prs:
                        found.append(f"{at}: PR #{op['pr']} merges, but it is not open")
                    open_prs.discard(op["pr"])
                else:
                    found.append(f"{at}: unknown op {kind}")
        check_deploy_versions()
    return found


def deploy_version_branch(branch):
    """Where `gflow deploy-version` runs: develop, release and hotfix
    branches, and the work branches that land on them."""
    return branch == "develop" or re.match(
        r"(release|hotfix|feature|fix|chore|docs|refactor|release-fix|hotfix-fix)/", branch) is not None


def deploy_version_problems(action, branches):
    """deployVersions must list every open branch where deploy-version runs,
    and only those, each as X.Y.Z+N (a release can carry -rc.N)."""
    listed = action.get("deployVersions")
    if listed is None:
        return ["are missing"]
    found = [f"list {b}, which does not exist" for b in listed if b not in branches]
    found += [f"list {b}, where gflow deploy-version refuses" for b in listed if b in branches and not deploy_version_branch(b)]
    found += [f"miss {b}" for b in sorted(branches) if deploy_version_branch(b) and b not in listed]
    found += [f"of {b} is '{v}', not X.Y.Z+N" for b, v in listed.items()
              if not re.fullmatch(r"\d+\.\d+\.\d+(-rc\.\d+)?\+\d+", v)]
    return found


def object_id(path):
    """Git's object id of the file, shortened: the same id for the same
    content."""
    return subprocess.run(["git", "hash-object", str(path)], check=True,
                          capture_output=True, text=True).stdout.strip()[:12]


def main():
    files = sorted(CYCLES.glob("*.json"))
    cycles = [(path, json.loads(path.read_text())) for path in files]
    found = [p for path, spec in cycles for p in problems(path.name, spec)]
    settings = [json.dumps(spec.get("settings"), sort_keys=True) for _, spec in cycles]
    found += [f"{path.name}: same settings as another cycle"
              for (path, _), s in zip(cycles, settings) if settings.count(s) > 1]
    if found:
        print(f"✖ spec/cycles has {len(found)} problems:", file=sys.stderr)
        for problem in found:
            print(f"  {problem}", file=sys.stderr)
        sys.exit(1)

    built_in = json.dumps([{"file": path.name, "id": object_id(path), "spec": spec}
                           for path, spec in cycles], ensure_ascii=False)
    # `</script>` in a text would end the script tag early. `<\/` is the
    # same JSON string.
    built_in = built_in.replace("</", "<\\/")
    page = TEMPLATE.read_text().replace("{{CYCLES_JSON}}", built_in, 1)
    PAGE.write_text(f"{GENERATED_NOTICE}\n{page}")
    print(f"✔ Rendered spec/replay.html from {len(cycles)} cycles in spec/cycles.")


if __name__ == "__main__":
    main()
